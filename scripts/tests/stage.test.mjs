import assert from 'node:assert/strict';
import test from 'node:test';
import React, { act } from 'react';
import { createRoot } from 'react-dom/client';
import { source, environment } from './helpers.mjs';
import { renderers } from './renderer.mock.mjs';
import { PerspectiveCamera, Vector3 } from 'three';

test('context restoration rebuilds Stage once, releases the old renderer and preserves gallery position', async (t) => {
  const env = await environment();
  const { Stage } = await source('src/immersive/Stage.tsx', { three: new URL('./renderer.mock.mjs', import.meta.url).href });
  const { projects } = await source('src/data/projects.ts');
  const progressRef = { current: { chapter: 'work', position: 1, progress: 1, workBlend: 1, overlay: 'contact' } };
  const workRef = { current: { items: projects, target: 3.2, position: 3.2, dragging: false, blockClickUntil: 0, ready: false, interactive: false, selectedIndex: null, selection: 0 } };
  const root = createRoot(env.q('#root'));
  const action = async (callback) => { await act(async () => { callback(); await env.settle(); }); };
  t.after(async () => { try { await action(() => root.unmount()); assert.deepEqual(env.errors, []); assert.ok(renderers.every((renderer) => renderer.disposed)); } finally { env.cleanup(); } });
  await action(() => root.render(React.createElement(React.StrictMode, null, React.createElement(Stage, { progressRef, workRef }))));
  await action(() => {});
  assert.equal(env.q('.im-stage').dataset.status, 'ready');
  assert.equal(renderers.filter((renderer) => !renderer.disposed).length, 1);
  const previous = renderers.at(-1);
  const eye = previous.camera.toArray();
  const canvas = env.q('canvas');
  const lost = new Event('webglcontextlost', { cancelable: true });
  await action(() => canvas.dispatchEvent(lost));
  assert.equal(lost.defaultPrevented, true);
  assert.equal(env.q('.im-stage').dataset.status, 'fallback');
  await action(() => canvas.dispatchEvent(new Event('webglcontextrestored')));
  await action(() => {});
  assert.equal(env.q('.im-stage').dataset.status, 'ready');
  assert.equal(previous.disposed, true);
  assert.equal(renderers.filter((renderer) => !renderer.disposed).length, 1);
  assert.equal(workRef.current.position, 3.2); assert.equal(workRef.current.target, 3.2);
  assert.equal(progressRef.current.overlay, 'contact');
  renderers.at(-1).camera.toArray().forEach((value, index) => assert.ok(Math.abs(value - eye[index]) < 1e-9));
});

test('selection advances the real camera and card transforms smoothly, preserves picking, then returns to the helix', async (t) => {
  const env = await environment({ width: 1440, height: 900 }); t.after(() => env.cleanup());
  const { createWorkOrbit } = await source('src/immersive/WorkOrbit.ts');
  const { projects } = await source('src/data/projects.ts');
  const orbit = createWorkOrbit({ capabilities: { getMaxAnisotropy: () => 1 } }, false);
  t.after(() => orbit.dispose());
  const state = { items: projects, target: 0, position: 0, selectedIndex: null, selection: 0, dragging: false, ready: false };
  const camera = new PerspectiveCamera(34, 1440 / 900, .1, 120);
  const eye = new Vector3(), aim = new Vector3();
  const frame = () => {
    orbit.advance(state, 1 / 60); orbit.cameraPose(state, camera.aspect, camera.fov, eye, aim);
    camera.position.copy(eye); camera.lookAt(aim); camera.updateMatrixWorld();
    orbit.update(state, camera, 1, 1 / 60, 1, false);
  };
  frame(); const wideZ = eye.z, restingCardZ = orbit.group.children[0].position.z;
  state.selectedIndex = 0; frame();
  assert.ok(state.selection > 0 && state.selection < .2, 'first frame begins the transition without snapping');
  for (let i = 0; i < 90; i++) frame();
  assert.ok(state.selection > .99);
  assert.ok(eye.z < wideZ - .5, 'camera moves closer to the selected card');
  assert.ok(orbit.group.children[0].position.z > restingCardZ + .17);
  assert.ok(orbit.group.children[0].scale.x > 1.019);
  assert.ok(orbit.group.children[0].material.uniforms.uReveal.value > .99, 'selection keeps the actual 3D card visible');
  assert.ok(orbit.group.children[1].material.uniforms.uReveal.value < .4);
  assert.equal(orbit.hitTest(camera, 720, 450, 1440, 900), 0, 'the transformed card remains clickable');
  state.selectedIndex = null;
  for (let i = 0; i < 120; i++) frame();
  assert.ok(Math.abs(eye.z - wideZ) < .001);
  assert.ok(orbit.group.children[1].material.uniforms.uReveal.value > .99);
});

test('dragging the home sculpture rotates it while vertical touch remains native', async (t) => {
  const env = await environment({ width: 1440, height: 900 });
  const { Stage } = await source('src/immersive/Stage.tsx', { three: new URL('./renderer.mock.mjs', import.meta.url).href });
  const { projects } = await source('src/data/projects.ts');
  const progressRef = { current: { chapter: 'home', position: 0, progress: 0, workBlend: 0, overlay: null } };
  const workRef = { current: { items: projects, target: 0, position: 0, dragging: false, ready: false, selectedIndex: null, selection: 0 } };
  const root = createRoot(env.q('#root'));
  const action = async (callback) => { await act(async () => { callback(); await env.settle(); }); };
  t.after(async () => { try { await action(() => root.unmount()); assert.deepEqual(env.errors, []); } finally { env.cleanup(); } });
  await action(() => root.render(React.createElement(Stage, { progressRef, workRef })));
  await action(() => {});
  const world = renderers.at(-1).scene.getObjectByName('home-world'); const before = world.rotation.y;
  const pointer = (type, x, y) => {
    const event = new MouseEvent(type, { bubbles: true, cancelable: true, button: 0, clientX: x, clientY: y });
    Object.defineProperty(event, 'pointerId', { value: 4 }); env.q('canvas').dispatchEvent(event); return event;
  };
  await action(() => { pointer('pointerdown', 700, 400); pointer('pointermove', 900, 402); pointer('pointerup', 900, 402); });
  assert.ok(world.rotation.y > before + .2);
  let vertical;
  await action(() => { pointer('pointerdown', 700, 400); vertical = pointer('pointermove', 702, 450); pointer('pointerup', 702, 450); });
  assert.equal(vertical.defaultPrevented, false);
});

test('context recovery retains an open project, its transition and shared environment', async (t) => {
  const env = await environment({ width: 1440, height: 900 });
  const { Stage } = await source('src/immersive/Stage.tsx', { three: new URL('./renderer.mock.mjs', import.meta.url).href });
  const { projects } = await source('src/data/projects.ts');
  const { createPresentation } = await source('src/immersive/projectPresentation.ts');
  const presentation = createPresentation(); Object.assign(presentation, { projectId: 'cars', phase: 'opening', progress: .65 });
  const progressRef = { current: { chapter: 'work', position: 1, progress: 1, workBlend: 1, overlay: null } };
  const workRef = { current: { items: projects, target: 2, position: 2, dragging: false, blockClickUntil: 0, ready: false, interactive: false, selectedIndex: 2, selection: 1, presentation } };
  const root = createRoot(env.q('#root'));
  const action = async (callback) => { await act(async () => { callback(); await env.settle(); }); };
  t.after(async () => { try { await action(() => root.unmount()); assert.deepEqual(env.errors, []); } finally { env.cleanup(); } });
  await action(() => root.render(React.createElement(Stage, { progressRef, workRef })));
  await action(() => {});
  const previous = renderers.at(-1), camera = previous.camera.clone();
  const previousSurroundings = previous.scene.getObjectByName('project-environment'); assert.equal(previousSurroundings.visible, true);
  await action(() => env.q('canvas').dispatchEvent(new Event('webglcontextlost', { cancelable: true })));
  assert.equal(presentation.ready, false);
  await action(() => env.q('canvas').dispatchEvent(new Event('webglcontextrestored')));
  await action(() => {});
  assert.equal(presentation.projectId, 'cars'); assert.equal(presentation.phase, 'opening'); assert.equal(presentation.progress, .65);
  assert.equal(workRef.current.position, 2); assert.equal(previous.disposed, true);
  assert.ok(renderers.at(-1).camera.distanceTo(camera) < 1e-9);
  assert.notEqual(renderers.at(-1).scene.getObjectByName('project-environment'), previousSurroundings);
  assert.equal(renderers.filter((renderer) => !renderer.disposed).length, 1);
});
